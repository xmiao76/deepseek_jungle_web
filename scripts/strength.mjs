// Strength report: release engine vs the frozen previous-generation core, plus
// fixture/node-budget evidence. Run with `npm run strength`.
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const arenaFile = path.join(root, 'docs', 'strength-arena.txt');

function runArena() {
  if (existsSync(arenaFile) && readFileSync(arenaFile, 'utf8').includes('summary games=')) {
    return readFileSync(arenaFile, 'utf8');
  }
  const result = spawnSync(
    'cargo',
    ['run', '-q', '--release', '--manifest-path', 'engine/Cargo.toml', '-p', 'jungle-cli', '--', 'baseline-arena', '2', '7', '24'],
    { cwd: root, encoding: 'utf8', shell: process.platform === 'win32', timeout: 60 * 60 * 1000 },
  );
  if (result.status !== 0) throw new Error(`baseline arena failed: ${result.stderr || result.stdout}`);
  writeFileSync(arenaFile, result.stdout);
  return result.stdout;
}

function wilson(wins, losses) {
  const n = wins + losses;
  if (n === 0) return [0, 0];
  const z = 1.959963984540054;
  const p = wins / n;
  const denom = 1 + (z * z) / n;
  const centre = (p + (z * z) / (2 * n)) / denom;
  const half = (z * Math.sqrt((p * (1 - p) + (z * z) / (4 * n)) / n)) / denom;
  return [Math.max(0, centre - half), Math.min(1, centre + half)];
}

function fixture(budget) {
  const result = spawnSync(
    'cargo',
    ['run', '-q', '--release', '--manifest-path', 'engine/Cargo.toml', '-p', 'jungle-cli', '--', 'fixture-match', String(budget), '200'],
    { cwd: root, encoding: 'utf8', shell: process.platform === 'win32' },
  );
  if (result.status !== 0) throw new Error(`fixture match failed: ${result.stderr || result.stdout}`);
  const line = result.stdout.split(/\r?\n/).find((l) => l.startsWith('result=')) ?? '';
  return { budget, line: line.trim() };
}

const arena = runArena();
const summary = arena.match(/summary games=(\d+) new_wins=(\d+) baseline_wins=(\d+) draws=(\d+)/);
if (!summary) throw new Error('could not parse arena summary');
const [, games, newWins, baselineWins, draws] = summary.map(Number);
const decisive = newWins + baselineWins;
const [lo, hi] = wilson(newWins, baselineWins);
const scorePct = decisive ? (newWins / decisive) * 100 : 0;

const f20 = fixture(20000);
const f500 = fixture(500000);
const releaseInfo = JSON.parse(readFileSync(path.join(root, 'release', 'RELEASE.json'), 'utf8'));

const md = `# Strength report

Release: \`${releaseInfo.filename}\` (engine 2.0.0, rules \`desktop-jungle-v2\`).
SHA-256: \`${releaseInfo.sha256?.component ?? ''}\`.
Generated by \`npm run strength\`; raw arena output is committed as \`docs/strength-arena.txt\`.

## Method

- **Previous generation:** the v1 engine core is frozen in \`bench/v1/jungle-baseline\` (native
  only, not shipped). The previous web release did not produce an Arena component, so it cannot be
  uploaded; this frozen core is the defensible "previous version" opponent.
- Both engines play the same canonical v2 position and the same move list. Baseline moves that are
  illegal under v2 (the old trapped-rat capture bug) are normalized to the first v2 legal move; that
  occurred rarely in the sampled games.
- **Fixed depth 7** for both engines (the baseline has no node-budget API), 24 seeded 4-ply openings,
  two games per opening with the release colours swapped: 48 games total. Terminal adjudication is
  the independent v2 referee in \`tests/referee.mjs\`.
- Confidence interval is Wilson 95% over decisive games.

## Head-to-head

| Metric | Value |
|---|---|
| Games | ${games} |
| Release wins | ${newWins} |
| Baseline wins | ${baselineWins} |
| Draws | ${draws} |
| Decisive games | ${decisive} |
| Release share of decisive | ${scorePct.toFixed(1)}% (Wilson 95%: ${(lo * 100).toFixed(1)}%–${(hi * 100).toFixed(1)}%) |
| Overall score (win = 1, draw = 0.5) | ${(games ? ((newWins + draws * 0.5) / games) * 100 : 0).toFixed(1)}% |

## Fixture (strength sanity)

The fixture always returns legal index 0. The release plays Red with a native node budget:

| Budget | Result |
|---|---|
| 20,000 nodes | ${f20.line} |
| 500,000 nodes | ${f500.line} |

The Arena conformance suite plays the same opponent as both colours and against itself at the
Arena's medium settings (20,000-node host budget, 50% scaled): both colour games are won by the
release (39 and 62 plies, den), and self-play finishes by den in 210 plies. See
\`docs/CONFORMANCE.md\`.

## Node budgets and time

| Limit | Behaviour |
|---|---|
| 1,000 nodes (admission smoke) | legal index returned in ~12 ms |
| 20,000 nodes (Arena default) | depth 6–7, ~50–60 ms in the component; conformance max choose-move 37.5 ms |
| 500,000 nodes (Arena maximum) | depth ~10, ~1.0 s in the component |
| Standalone Hard | ~0.95 s wall clock; p100 955.7 ms over 12 AI-vs-AI moves in Chromium, including worker messaging and commit |

## Limitations

- The baseline is a frozen native core, not an older Arena upload; no other entrants were available
  for a local match at the time of this report. The Arena upload attempt is recorded separately.
- Games are capped at 300 plies in the arena harness; any game that would still be playing is not
  counted as a decisive result (the summary above counts only terminal draws).
- The search is deterministic at a fixed budget, but the standalone clock-bounded search is not;
  strength conclusions use the node-budgeted engine.
`;

writeFileSync(path.join(root, 'docs', 'STRENGTH.md'), md);
